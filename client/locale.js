/**
 * Fill `{name}` placeholders in a localized template.
 *
 * @param t - translate function bound to {@link NS}.
 * @param key - dictionary key.
 * @param vars - placeholder values.
 * @returns the localized string, with unknown keys left as-is.
 */
export function fmt(t, key, vars) {
  let text
  try {
    text = t(key)
  } catch {
    text = key
  }
  if (typeof text !== 'string') text = key
  if (!vars) return text
  for (const [name, value] of Object.entries(vars)) {
    text = text.split('{' + name + '}').join(String(value))
  }
  return text
}

/**
 * Message from an unknown thrown value.
 *
 * @param error - anything a rejected promise may carry.
 * @returns a printable message.
 */
export function errorMessage(error) {
  if (error && typeof error.message === 'string' && error.message) return error.message
  if (typeof error === 'string' && error) return error
  return 'Unknown error'
}

/**
 * Localized text for a Host error.
 *
 * The Host's own messages are English and are shown verbatim by default (that
 * keeps unknown failures honest). A few codes instead carry a decision the user
 * has to act on — "you must type the password this profile never saved" — so
 * they are rendered in the panel's language and the raw message is dropped.
 *
 * @param t - locale translate function.
 * @param error - anything a rejected promise may carry; `code` is honoured.
 * @returns a printable, possibly localized message.
 */
export function hostErrorText(t, error) {
  const code = error && typeof error.code === 'string' ? error.code : ''
  if (code === 'MISSING_SECRET') return t('errMissingSecret')
  if (code === 'AI_SECRET_DENIED') return t('errAiSecretDenied')
  if (code === 'PROFILE_NOT_FOUND') return t('errProfileNotFound')
  return errorMessage(error)
}
